/** Writes supabase/seed.sql from the same generator the app uses in local mode. Run: npm run seed:sql */
import { writeFileSync } from "node:fs";
import { generateSeed } from "../src/lib/seed";
import { DEFAULT_RULES } from "../src/lib/rules";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rows = (table: string, cols: string[], values: unknown[][]) =>
  `insert into ${table} (${cols.join(", ")}) values\n${values.map((r) => `  (${r.map(q).join(", ")})`).join(",\n")};\n`;

const d = generateSeed();
const cycleId = "2026-2027";
const sql = [
  "-- Generated by scripts/export-seed.ts. All people are fictional.\n",
  rows("posts", ["id", "city", "country", "region", "subregion", "lat", "lng", "post_type", "hardship_pct", "language", "tour_years"],
    d.posts.map((p) => [p.id, p.city, p.country, p.region, p.subregion, p.lat, p.lng, p.type, p.hardship, p.language, p.tourYears])),
  rows("positions", ["id", "post_id", "grade", "title", "specialty", "language_req"],
    d.positions.map((p) => [p.id, p.postId, p.grade, p.title, p.specialty, p.languageReq])),
  rows("officers", ["id", "display_name", "grade", "languages", "position_id", "ted", "last_hardship_year", "training_language", "training_until", "onward_position_id"],
    d.officers.map((o) => [o.id, o.name, o.grade, o.languages, o.positionId, o.ted, o.lastHardship, o.training?.language, o.training?.until, o.training?.onwardPositionId])),
  `insert into cycles (id, label, is_active, rules) values (${q(cycleId)}, ${q(DEFAULT_RULES.cycleLabel)}, true, ${q(JSON.stringify(DEFAULT_RULES))}::jsonb);\n`,
  rows("bids", ["cycle_id", "officer_id", "position_id", "rank", "submitted_at"],
    d.bids.map((b) => [cycleId, b.officerId, b.positionId, b.rank, d.submitted.includes(b.officerId) ? "2026-11-15T17:00:00Z" : null])),
].join("\n");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql: ${d.posts.length} posts, ${d.positions.length} positions, ${d.officers.length} officers, ${d.bids.length} bids`);
